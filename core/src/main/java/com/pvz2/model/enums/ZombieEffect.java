package com.pvz2.model.enums;

/**
 * افکت‌های وضعیتی که می‌توانند روی زامبی اعمال شوند.
 * هر افکت مدت زمان باقیمانده دارد.
 */
public enum ZombieEffect {
    CHILLED,        // کُند شده توسط تیر یخی
    FROZEN,         // کاملاً یخ‌زده (حرکت ندارد)
    HYPNOTIZED,     // هیپنوتیزم شده (به سمت زامبی‌ها حمله می‌کند)
    BURNING,        // در حال سوختن (آسیب DoT آتش)
    SLOWED,         // کند شده (از اثرات مختلف)
    STUNNED         // از کار افتاده موقت
}
