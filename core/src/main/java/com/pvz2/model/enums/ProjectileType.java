package com.pvz2.model.enums;

/**
 * انواع پرتابه‌های گیاهان.
 * نوع پرتابه بر آسیب و تعامل با زامبی‌ها و محیط تأثیر دارد.
 */
public enum ProjectileType {
    NORMAL,     // معمولی
    FIRE,       // آتشین (آسیب x2، یخ را ذوب می‌کند)
    ICE,        // یخی (کاهش سرعت زامبی)
    POISON,     // سمی (زره را نادیده می‌گیرد، آسیب DoT)
    LOBBED,     // پرتابی هوایی (از موانع رد می‌شود)
    STRIKE      // نفوذکننده (از چند زامبی رد می‌شود)
}
