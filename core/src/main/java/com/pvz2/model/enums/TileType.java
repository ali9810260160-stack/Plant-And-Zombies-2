package com.pvz2.model.enums;

/**
 * انواع خانه‌های زمین بازی در فصل‌های مختلف.
 * هر فصل خانه‌های خاص خودش را دارد.
 */
public enum TileType {
    // --- مصر باستان ---
    EGYPT_NORMAL,       // زمین معمولی مصر
    TOMBSTONE,          // سنگ قبر (مانع تیر افقی، 700 HP)

    // --- غارهای یخی ---
    CAVE_NORMAL,        // زمین معمولی غار
    ICY_GROUND,         // زمین یخزده (گیاه/زامبی داخل دارد، قابل ذوب)
    SLIPPERY_UP,        // زمین لیز به بالا
    SLIPPERY_DOWN,      // زمین لیز به پایین

    // --- ساحل مواج ---
    BEACH_NORMAL,       // زمین ساحلی معمولی
    WATER,              // آب (فقط گیاهان آبی یا lily pad)
    LOW_TIDE,           // ساحل پست (زامبی از زیر ظاهر می‌شود)

    // --- قرون وسطی ---
    DARK_NORMAL,        // زمین معمولی عصر تاریکی
    DARK_TOMBSTONE,     // سنگ قبر قرون وسطی (ممکن است خورشید/غذا داشته باشد)
    NECROMANCY          // نکرومنسی (با قبر روی آن، زامبی تولید می‌کند)
}
